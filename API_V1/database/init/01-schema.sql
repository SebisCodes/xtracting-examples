-- One row per task and language. This is the table a collector reads to decide
-- what it already has: every completed task writes exactly one row here, in the
-- same transaction as its data, even when the extraction produced nothing at
-- all. A data table can legitimately be empty for a task; this one cannot.
CREATE TABLE processed_data.tasks (
    date_added           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    text_name            TEXT NOT NULL,
    text_project         TEXT NOT NULL DEFAULT '',
    text_language        TEXT NOT NULL DEFAULT 'English',
    text_task_id         TEXT NOT NULL DEFAULT '',
    bigint_id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    text_job_id          TEXT NOT NULL DEFAULT '',
    integer_task_index   INTEGER NOT NULL DEFAULT 0,
    text_status          TEXT NOT NULL DEFAULT '',
    text_source_uri      TEXT NOT NULL DEFAULT '',
    -- Also here, so "has this file been extracted?" can be answered without
    -- touching a data table that may legitimately be empty.
    text_content_hash    TEXT NOT NULL DEFAULT '',
    text_tag             TEXT,
    text_error           TEXT,
    float_cost_chf       DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    bigint_processing_ms BIGINT,
    date_commissioned    TIMESTAMPTZ,
    date_evaluated       TIMESTAMPTZ,
    PRIMARY KEY (date_added, bigint_id)
);

DO $$
DECLARE
    data_tables TEXT[] := ARRAY[
        'sources', 'entities', 'locations', 'events', 'ratings', 'connections',
        'attributes', 'market_insights', 'source_importances_by_perspective',
        'event_entities', 'tasks'
    ];
    t TEXT;
    seg TEXT;
BEGIN
    FOREACH t IN ARRAY data_tables LOOP
        EXECUTE format(
            $f$SELECT create_hypertable('processed_data.%I', 'date_added',
                                        chunk_time_interval => INTERVAL '1 day')$f$, t);

        -- Segment by what analyses actually filter on. text_name is the
        -- selective one: a given name sits in a few segments, so a name lookup
        -- skips the rest without decompressing them. text_project and
        -- text_language are not selective - every chunk holds every project and
        -- every language - but naming them here stores each value once per
        -- segment instead of compressing it as a column, which makes the chunk
        -- smaller rather than larger. See the header for the measurements.
        SELECT CASE WHEN EXISTS (
                   SELECT 1 FROM information_schema.columns
                   WHERE table_schema = 'processed_data'
                     AND table_name = t AND column_name = 'text_type')
               THEN 'text_name, text_type, text_project, text_language'
               ELSE 'text_name, text_project, text_language'
               END
          INTO seg;

        EXECUTE format($f$
            ALTER TABLE processed_data.%I SET (
                timescaledb.compress,
                timescaledb.compress_segmentby = %L,
                timescaledb.compress_orderby = 'date_added DESC'
            )
        $f$, t, seg);
        -- THIRTY DAYS, NOT ONE.
        --
        -- A day meant that all but the newest chunk was compressed, and the
        -- dashboard reads the whole archive rather than its newest day: every
        -- filtered scan then pays to decompress what it walks over. Measured
        -- on a real archive, one place search planned over 550 chunks and
        -- spent eight seconds in them.
        --
        -- Thirty days keeps the working set - what anybody is looking at
        -- while it is being collected and checked - readable at full speed,
        -- and still compresses everything behind it, which is where the
        -- volume is. The number is the customer's: a month is how far back a
        -- question about "recent" reaches here.
        -- The policy lives in init/05-policies.sql, which owns every retention and
        -- compression number in one place and, unlike this file, may be applied to an
        -- archive that already exists.

        -- The three identity columns, each on its own. Plain B-tree, not
        -- partitioning dimensions - see the header.
        EXECUTE format($f$CREATE INDEX idx_%s_project  ON processed_data.%I (text_project)$f$, t, t);
        EXECUTE format($f$CREATE INDEX idx_%s_language ON processed_data.%I (text_language)$f$, t, t);
        EXECUTE format($f$CREATE INDEX idx_%s_task     ON processed_data.%I (text_task_id)$f$, t, t);
        -- And the combination a collector actually asks for: which tasks of
        -- this project are already here. Time-ordered, because it only ever
        -- looks at a short recent window.
        EXECUTE format(
            $f$CREATE INDEX idx_%s_project_task ON processed_data.%I
                 (text_project, text_task_id, date_added DESC)$f$, t, t);
    END LOOP;
END
$$;

