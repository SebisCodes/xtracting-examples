-- ============================================================
-- monitoring
--
-- Carries the same three columns as everything else. A run covers many tasks,
-- so text_task_id is usually empty here - it is present so a script splitting
-- an archive by project can treat every table in the database identically
-- instead of keeping a list of exceptions.
-- ============================================================

CREATE TABLE monitoring.collector_runs (
    date_added        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    text_name         TEXT NOT NULL,
    text_project      TEXT NOT NULL DEFAULT '',
    text_language     TEXT NOT NULL DEFAULT 'English',
    text_task_id      TEXT NOT NULL DEFAULT '',
