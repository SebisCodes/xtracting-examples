-- One row per (event, entity) pair.
--
-- An event belongs to its document and may also name what it is about, in an
-- Events[].entityids list. A list needs rows, not a column: "which events touched
-- this plant" has to be answerable from the entity side too, and an array would
-- make that a scan while every other relationship here is a join.
--
-- Modelled on connections, which is the other table whose whole job is to hold a
-- reference. The event is carried by its bigint_id because an event has no id of
-- its own in the extraction - unlike an entity, which brings "ent:...".
--
-- An event with no entityids writes no rows at all. That is the ordinary case
-- and not a gap: it means the event is about the document rather than anything
-- in it.
CREATE TABLE processed_data.event_entities (
    date_added              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    text_name               TEXT NOT NULL,
    text_project            TEXT NOT NULL DEFAULT '',
    text_language           TEXT NOT NULL DEFAULT 'English',
    text_task_id            TEXT NOT NULL DEFAULT '',
    bigint_id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    text_job_id             TEXT,
    text_fk_source_id       TEXT,
    bigint_fk_event_id      BIGINT,
    text_fk_entity_id       TEXT,
    date_commissioned       TIMESTAMPTZ,
    date_evaluated          TIMESTAMPTZ,
    PRIMARY KEY (date_added, bigint_id)
);

