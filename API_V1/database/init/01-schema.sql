-- ============================================================
-- Xtracting archive - schema
-- PostgreSQL 18 + TimescaleDB
--
-- One database for extraction results, in every language you asked for.
--
-- THREE COLUMNS ARE ON EVERY TABLE, and they are what makes this worth sharing
-- as a schema rather than keeping private:
--
--   text_project    which project the row belongs to. An API key is bound to
--                   one project, so several can share an archive and still be
--                   pulled apart later without ambiguity.
--   text_language   which language version this row is. The English original is
--                   stored as 'English'; every requested translation is stored
--                   as its own complete set of rows with the same task id.
--   text_task_id    which task produced it. This is what a collector reads to
--                   decide what it has already archived, and what you delete by
--                   if you ever need to remove one task's output.
--
-- All three are plain B-tree indexes on every table, deliberately NOT hypertable
-- dimensions. Partitioning by them would make chunks that never fill, and the
-- queries they serve are equality filters, which a B-tree answers better than a
-- partition ever will.
--
-- SEPARABILITY. Because every row carries its project, and because nothing is
-- ever shared between projects, an archive that outgrows one database can be
-- split by copying rows WHERE text_project = '...'. Nothing has to be untangled
-- first. That is also why the same vocabulary entry is stored once per project
-- rather than once globally - see the uniqueness rule below.
--
-- There is no table for raw task text. This database is for results. The
-- submitted content stays with you and is deleted on the platform after an
-- hour; keeping a second copy here would quietly undo that.
-- ============================================================

CREATE EXTENSION IF NOT EXISTS timescaledb CASCADE;

CREATE SCHEMA IF NOT EXISTS processed_data;


CREATE SCHEMA IF NOT EXISTS monitoring;

-- ============================================================
-- Vocabularies
--
-- Plain tables, NOT hypertables, and that is deliberate. A vocabulary grows
-- with the number of distinct names, which saturates - it is not a time series,
-- and partitioning it by day would produce chunks of four rows.
--
-- More importantly it lets the uniqueness rule be enforced by the database:
--
--     UNIQUE (text_name, text_project, text_language)
--
-- A hypertable cannot have a unique index that omits its partitioning column,
-- so here the constraint would have to include date_added - and then an insert
-- a second later is a different row and ON CONFLICT never fires. The result is
-- a vocabulary that gains one duplicate per task, forever.
--
-- The same type name in two projects is stored TWICE, once per project. That is
-- the point: 'Machine' in project A and 'Machine' in project B are not one
-- entry with two owners, and an archive that merged them could not be split
-- apart again.
-- ============================================================

DO $$
DECLARE
    type_tables TEXT[] := ARRAY[
        'source_types', 'entity_types', 'event_types', 'location_types',
        'perspective_types', 'rating_types', 'connection_types', 'relation_types',
        'attribute_types', 'unit_types', 'importance_types',
        'market_topic_types', 'outlook_types', 'sentiment_types',
        'rating_values', 'trustlist_types'
    ];
    t TEXT;
BEGIN
    FOREACH t IN ARRAY type_tables LOOP
        EXECUTE format($f$
            CREATE TABLE processed_data.%I (
                bigint_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                date_added       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                text_name        TEXT NOT NULL,
                text_project     TEXT NOT NULL DEFAULT '',
                text_language    TEXT NOT NULL DEFAULT 'English',
                text_task_id     TEXT NOT NULL DEFAULT '',
                text_job_id      TEXT NOT NULL DEFAULT '',
                text_description TEXT NOT NULL DEFAULT '',
                float_value      DOUBLE PRECISION,
                bool_enabled     BOOLEAN NOT NULL DEFAULT true,
                UNIQUE (text_name, text_project, text_language)
            )
        $f$, t);

        EXECUTE format($f$CREATE INDEX idx_%s_project  ON processed_data.%I (text_project)$f$, t, t);
        EXECUTE format($f$CREATE INDEX idx_%s_language ON processed_data.%I (text_language)$f$, t, t);
        EXECUTE format($f$CREATE INDEX idx_%s_task     ON processed_data.%I (text_task_id)$f$, t, t);
    END LOOP;
END
$$;

ALTER TABLE processed_data.connection_types ADD COLUMN bool_reversed BOOLEAN NOT NULL DEFAULT false;

-- ============================================================
-- Data tables
--
-- Hypertables on date_added, one-day chunks, compressed a day after each chunk
-- closes.
--
-- Keyed by identity, never by name. A structured extraction can legitimately
-- repeat a name: a location called "EU" belonging to two entities of one task,
-- an attribute called "Retention Period" on two entities. Those are two records,
-- not one written twice. Keying on the name made the second one a duplicate and
-- aborted the whole job's transaction, which cost four jobs before it was
-- found. date_added leads the key because TimescaleDB requires the
-- partitioning column in every unique index. Recycling by name is the *_types
-- tables' job, and they keep their UNIQUE (text_name, text_project, text_language).
--
-- text_fk_* columns carry no formal foreign keys: a hypertable cannot be the
-- target of one. The collector resolves references before it writes.
-- ============================================================

CREATE TABLE processed_data.sources (
    date_added              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    text_name               TEXT NOT NULL,
    text_project            TEXT NOT NULL DEFAULT '',
    text_language           TEXT NOT NULL DEFAULT 'English',
    text_task_id            TEXT NOT NULL DEFAULT '',
    bigint_id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    text_job_id             TEXT,
    text_source_id          TEXT,
    text_uri                TEXT NOT NULL DEFAULT '',
    -- sha256 of exactly what was submitted, hex. Compare it against a file on
    -- disk and you know whether that file has already been extracted in this
    -- state - without re-uploading it, and without trusting a filename or a
    -- modification date. A whole directory becomes a set of hashes to diff
    -- against this column.
    text_content_hash       TEXT NOT NULL DEFAULT '',
    text_type               TEXT NOT NULL DEFAULT '',
    text_importance         TEXT NOT NULL DEFAULT '',
    text_summary            TEXT NOT NULL DEFAULT '',
    text_reason             TEXT NOT NULL DEFAULT '',
    text_keywords           TEXT NOT NULL DEFAULT '',
    text_evidences          TEXT,
    bool_trustful           BOOLEAN NOT NULL DEFAULT false,
    -- Both nullable: a document that does not state when it was written has no
    -- creation date, and the extraction returns null rather than a guess. There
    -- is deliberately no date_fetched - the model cannot know when a document
    -- was retrieved, and asked for it anyway it invented one.
    date_written            TIMESTAMPTZ,
    date_edited             TIMESTAMPTZ,
    -- When the task was commissioned and when its evaluation finished. Both
    -- come from the API; without them a row cannot be placed on a timeline
    -- other than by when this collector happened to fetch it.
    date_commissioned       TIMESTAMPTZ,
    date_evaluated          TIMESTAMPTZ,
    PRIMARY KEY (date_added, bigint_id)
);

